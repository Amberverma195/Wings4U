const React = require('react');
const { act, create } = require('react-test-renderer');
global.IS_REACT_ACT_ENVIRONMENT = true;
const mockCart = { locationId: 'store', items: [], fulfillmentType: 'DELIVERY', scheduledFor: null, driverTipPercent: 'none' };
const mockPromo = { promoCode: null, applyWingsReward: false, applyPromoCode: jest.fn() };
const mockSession = { loaded: true, authenticated: true, user: { id: 'customer' } };
jest.mock('react-native', () => ({ ActivityIndicator: 'ActivityIndicator', Modal: 'Modal', Pressable: 'Pressable', ScrollView: 'ScrollView', Text: 'Text', TouchableOpacity: 'TouchableOpacity', View: 'View', StyleSheet: { create: x => x } }));
jest.mock('react-native-safe-area-context', () => ({ SafeAreaView: 'SafeAreaView' }));
jest.mock('lucide-react-native', () => ({ Info: 'Info' }));
jest.mock('expo-router', () => ({ useRouter: () => ({ push: jest.fn() }) }));
jest.mock('../src/context/cart', () => ({ useCart: () => mockCart }));
jest.mock('../src/context/promo', () => ({ usePromo: () => mockPromo }));
jest.mock('../src/context/session', () => ({ useSession: () => mockSession }));
jest.mock('../src/hooks/use-account-data', () => ({ useAccountData: () => ({ data: {} }) }));
jest.mock('../src/lib/api', () => ({ apiJson: jest.fn() }));
const { apiJson } = require('../src/lib/api');
const { CartCoupons } = require('../src/components/cart-coupons');
const text = node => typeof node === 'string' ? node : Array.isArray(node) ? node.map(text).join('') : text(node?.children ?? '');
let renderer;
afterEach(async () => { if (renderer) await act(async () => renderer.unmount()); renderer = null; });
test.each(['PICKUP', 'DELIVERY'])('first-order details are associated by ID and preserve explicit Apply (%s)', async fulfillment => {
  jest.clearAllMocks(); mockCart.fulfillmentType = fulfillment;
  const offers = [{ id: 'first-order-deal:store', code: 'CUSTOMWELCOME', name: 'Renamed' },
    { id: 'other', code: 'MYFIRSTORDER', name: 'First order deal' }].map(p => ({ ...p, discountType: 'PERCENT', discountValue: 15, minSubtotalCents: 0, eligibleFulfillmentType: 'BOTH' }));
  apiJson.mockImplementation(async path => ({ data: path.includes('promotions') ? offers : null }));
  const requestSelection = jest.fn(async () => ({ applied_promo_code: 'CUSTOMWELCOME' }));
  await act(async () => { renderer = create(React.createElement(CartCoupons, { quote: null, requestSelection })); });
  await act(async () => renderer.root.findByProps({ accessibilityLabel: 'See coupons & rewards' }).props.onPress());
  const first = renderer.root.findByProps({ accessibilityLabel: 'Apply coupon CUSTOMWELCOME' });
  expect(text(renderer.root.findByType('ScrollView'))).toContain('75 & 100 Wing Party Specials are excluded from all coupons.');
  const other = renderer.root.findByProps({ accessibilityLabel: 'Apply coupon MYFIRSTORDER' });
  const note = 'First order only. Pickup & delivery · Lunch Specials eligible. Excludes 75 & 100 Wing Party Specials.';
  expect(text(first)).toContain(note); expect(text(other)).not.toContain(note);
  expect(first.props.accessibilityHint).toBe(note); expect(other.props.accessibilityHint).toBeUndefined();
  expect(first.findByType('Info').props.accessible).toBe(false);
  expect(requestSelection).not.toHaveBeenCalled();
  await act(async () => first.props.onPress());
  expect(requestSelection).toHaveBeenCalledWith({ promoCode: 'CUSTOMWELCOME', applyWingsReward: false });
  expect(mockPromo.applyPromoCode).toHaveBeenCalledWith('CUSTOMWELCOME');
});
